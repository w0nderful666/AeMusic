package com.aemusic.design.theme

import androidx.compose.ui.unit.dp

/**
 * Small spacing scale for recurring layout rhythm.
 *
 * A one-off measurement with real design meaning may still use a local literal.  This scale exists
 * to keep ordinary layout rhythm consistent, not to ban every dp literal in the project.
 */
object AeSpacing {
    val xxs = 4.dp
    val xs = 8.dp
    val sm = 12.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
    val xxl = 48.dp
}
